#!/usr/bin/env node
// Derive per-band theme counts from the shipped puzzle shards.
//
//   node scripts/build-puzzle-theme-index.mjs     (runs after `npm run puzzles:build`)
//
// Emits src/data/puzzleThemeCounts.generated.ts: for every theme, how many
// puzzles each 100-point rating band holds. The Puzzles page uses it to
//
//   - show "fork · 1 740 near your level" in the theme picker without
//     fetching a shard, and grey out themes that barely exist there, and
//   - pick a rating window wide enough to fill a run of a rare theme up
//     front, instead of discovering it's too narrow one ~400 KB shard at a
//     time (`windowForTheme` in queue.ts).
//
// It reads the SHARDS rather than the Lichess CSV, so it needs no 300 MB
// download and can be re-run on its own. The output carries the build id it
// was derived from; `puzzleThemeCounts.test.ts` fails if that drifts from
// PUZZLE_BUILD_ID, which is the guard against refreshing the corpus without
// re-running this.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const META = readFileSync(join(ROOT, 'src/data/puzzles.meta.generated.ts'), 'utf8');
const OUT = join(ROOT, 'src/data/puzzleThemeCounts.generated.ts');

const buildId = JSON.parse(META.match(/PUZZLE_BUILD_ID = ("[^"]+")/)[1]);
const themes = JSON.parse(META.match(/PUZZLE_THEMES: readonly string\[\] = (\[.*?\])/)[1]);
const bands = 1 + Math.max(...JSON.parse(META.match(/PUZZLE_SHARDS: readonly PuzzleShardMeta\[\] = (\[.*?\])/)[1]).map((s) => s.band));

const dir = join(ROOT, 'public/puzzles', buildId);
const counts = Object.fromEntries(themes.map((t) => [t, new Array(bands).fill(0)]));
for (const file of readdirSync(dir)) {
  const band = Number(file.match(/^b(\d+)-/)[1]);
  for (const line of readFileSync(join(dir, file), 'utf8').split('\n')) {
    if (!line) continue;
    const codes = line.split('\t')[4] ?? '';
    for (let i = 0; i + 2 <= codes.length; i += 2) {
      const name = themes[parseInt(codes.slice(i, i + 2), 36)];
      if (name) counts[name][band]++;
    }
  }
}

const body =
  `// AUTO-GENERATED by scripts/build-puzzle-theme-index.mjs — do not edit by hand.\n` +
  `// Puzzles per theme per 100-point rating band (index = band, as in PUZZLE_SHARDS).\n\n` +
  `/** The PUZZLE_BUILD_ID these counts were derived from. */\n` +
  `export const THEME_COUNTS_BUILD_ID = ${JSON.stringify(buildId)};\n\n` +
  `export const PUZZLE_THEME_BAND_COUNTS: Readonly<Record<string, readonly number[]>> = {\n` +
  Object.entries(counts)
    .map(([t, c]) => `  ${JSON.stringify(t)}: [${c.join(',')}],`)
    .join('\n') +
  `\n};\n`;
writeFileSync(OUT, body);
console.log(`Wrote ${OUT} (${themes.length} themes × ${bands} bands, build ${buildId})`);
